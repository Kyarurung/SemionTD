// 강령술사 애니메이션: idle / walk / attack / death.
//
// 키프레임 회전 부호는 orc_warrior_anims.js 머리말과 같습니다.
//  x < 0: 몸통·머리는 앞으로 숙이고, 아래로 뻗은 팔·다리는 끝이 뒤로 갑니다.
//  z > 0: 오른팔(+x)이 바깥으로 벌어집니다. 왼팔은 z < 0이 바깥입니다.
// 지팡이 방향은 오른 윗팔 + 아래팔 + 손목 x 회전 합이 90이면 곧게 위, 0이면 앞으로 수평입니다.
(function (global) {
    function necromancerAnimations(B) {
        const A = (name, length, loop, tracks) => InvasionBB.animation(B, name, length, loop, tracks);
        // 지팡이를 세워 짚고, 왼손은 영혼 구슬을 받쳐 앞으로 내밉니다.
        const hold = {
            right_arm: [0, 0, 4], right_forearm: [90, 0, 0], right_hand: [0, 0, 0],
            left_arm: [15, -10, 0], left_forearm: [60, 0, 0],
        };
        const keep = (len) => Object.fromEntries(Object.entries(hold).map(([k, v]) => [k, { rotation: [[0, v], [len, v]] }]));

        // ------------------------------------------------------------ idle
        // 등을 조금 굽히고 서서, 구슬을 든 왼손이 천천히 오르내립니다. 망토가 흔들립니다.
        A('idle', 3.0, 'loop', Object.assign(keep(3.0), {
            body: { position: [[0, [0, 0, 0]], [1.5, [0, -0.3, 0]], [3.0, [0, 0, 0]]] },
            torso: { rotation: [[0, [-4, 0, 0]], [1.5, [-6, 0, 0]], [3.0, [-4, 0, 0]]] },
            head: { rotation: [[0, [6, 0, 0]], [1.0, [6, 10, 0]], [2.0, [6, -8, 0]], [3.0, [6, 0, 0]]] },
            left_forearm: { rotation: [[0, hold.left_forearm], [1.5, [70, 0, 0]], [3.0, hold.left_forearm]] },
            cloak: { rotation: [[0, [0, 0, 0]], [1.5, [3, 0, 1]], [3.0, [0, 0, 0]]] },
        }));

        // ------------------------------------------------------------ walk
        const T = 1.2, q = T / 4, h = T / 2, t3 = 3 * T / 4;
        A('walk', T, 'loop', Object.assign(keep(T), {
            right_leg: { rotation: [[0, [0, 0, 0]], [q, [18, 0, 0]], [h, [0, 0, 0]], [t3, [-16, 0, 0]], [T, [0, 0, 0]]] },
            left_leg: { rotation: [[0, [0, 0, 0]], [q, [-16, 0, 0]], [h, [0, 0, 0]], [t3, [18, 0, 0]], [T, [0, 0, 0]]] },
            right_shin: { rotation: [[0, [-4, 0, 0]], [q, [0, 0, 0]], [h, [-4, 0, 0]], [t3, [-18, 0, 0]], [T, [-4, 0, 0]]] },
            left_shin: { rotation: [[0, [-4, 0, 0]], [q, [-18, 0, 0]], [h, [-4, 0, 0]], [t3, [0, 0, 0]], [T, [-4, 0, 0]]] },
            torso: { rotation: [[0, [-6, 0, 0]], [q, [-6, -3, 1]], [h, [-6, 0, 0]], [t3, [-6, 3, -1]], [T, [-6, 0, 0]]] },
            body: { position: [[0, [0, 0, 0]], [q, [0, -0.4, 0]], [h, [0, 0, 0]], [t3, [0, -0.4, 0]], [T, [0, 0, 0]]] },
            cloak: { rotation: [[0, [10, 0, 0]], [h, [14, 0, 0]], [T, [10, 0, 0]]] },
        }));

        // ------------------------------------------------------------ attack
        // 소환: 두 팔을 머리 위로 치켜들어 힘을 모았다가(0.55초) 지팡이와 왼손을 땅 쪽으로 내리꽂습니다(0.8초).
        A('attack', 1.4, 'once', {
            right_arm: { rotation: [[0, hold.right_arm], [0.55, [160, 0, 12]], [0.8, [70, 0, 4]], [1.0, [68, 0, 4]], [1.4, hold.right_arm]] },
            right_forearm: { rotation: [[0, hold.right_forearm], [0.55, [0, 0, 0]], [0.8, [0, 0, 0]], [1.4, hold.right_forearm]] },
            right_hand: { rotation: [[0, hold.right_hand], [0.55, [-60, 0, 0]], [0.8, [-95, 0, 0]], [1.0, [-95, 0, 0]], [1.4, hold.right_hand]] },
            left_arm: { rotation: [[0, hold.left_arm], [0.55, [160, 0, -15]], [0.8, [60, 0, -8]], [1.0, [58, 0, -8]], [1.4, hold.left_arm]] },
            left_forearm: { rotation: [[0, hold.left_forearm], [0.55, [0, 0, 0]], [0.8, [0, 0, 0]], [1.4, hold.left_forearm]] },
            torso: { rotation: [[0, [-4, 0, 0]], [0.55, [10, 0, 0]], [0.8, [-20, 0, 0]], [1.0, [-18, 0, 0]], [1.4, [-4, 0, 0]]] },
            head: { rotation: [[0, [6, 0, 0]], [0.55, [-12, 0, 0]], [0.8, [14, 0, 0]], [1.4, [6, 0, 0]]] },
            body: { position: [[0, [0, 0, 0]], [0.55, [0, 0.8, 0]], [0.8, [0, -1, 0]], [1.0, [0, -1, 0]], [1.4, [0, 0, 0]]] },
            cloak: { rotation: [[0, [0, 0, 0]], [0.55, [-4, 0, 0]], [0.8, [18, 0, 0]], [1.4, [0, 0, 0]]] },
            left_leg: { rotation: [[0, [0, 0, 0]], [0.8, [14, 0, 0]], [1.4, [0, 0, 0]]] },
            right_leg: { rotation: [[0, [0, 0, 0]], [0.8, [-10, 0, 0]], [1.4, [0, 0, 0]]] },
        });

        // ------------------------------------------------------------ death
        // 지팡이를 놓치며 무릎 꿇고, 앞으로 쓰러집니다.
        A('death', 1.8, 'hold', {
            root: {
                rotation: [[0, [0, 0, 0]], [0.7, [0, 0, 0]], [1.3, [-90, 0, 4]], [1.45, [-86, 0, 4]], [1.6, [-90, 0, 4]]],
                position: [[0, [0, 0, 0]], [0.6, [0, -5, 0]], [0.7, [0, -5, 0]], [1.3, [0, 3, 0]], [1.6, [0, 3, 0]]],
            },
            right_leg: { rotation: [[0, [0, 0, 0]], [0.6, [75, 0, 0]], [0.7, [75, 0, 0]], [1.3, [8, 0, 3]], [1.8, [8, 0, 3]]] },
            left_leg: { rotation: [[0, [0, 0, 0]], [0.6, [70, 0, 0]], [0.7, [70, 0, 0]], [1.3, [3, 0, -3]], [1.8, [3, 0, -3]]] },
            right_shin: { rotation: [[0, [0, 0, 0]], [0.6, [-90, 0, 0]], [0.7, [-90, 0, 0]], [1.3, [-10, 0, 0]], [1.8, [-10, 0, 0]]] },
            left_shin: { rotation: [[0, [0, 0, 0]], [0.6, [-85, 0, 0]], [0.7, [-85, 0, 0]], [1.3, [-6, 0, 0]], [1.8, [-6, 0, 0]]] },
            right_arm: { rotation: [[0, hold.right_arm], [0.6, [20, 0, 10]], [1.3, [160, 0, 20]], [1.8, [165, 0, 22]]] },
            right_forearm: { rotation: [[0, hold.right_forearm], [0.6, [20, 0, 0]], [1.3, [0, 0, 0]], [1.8, [0, 0, 0]]] },
            left_arm: { rotation: [[0, hold.left_arm], [0.6, [30, 0, -10]], [1.3, [150, 0, -25]], [1.8, [160, 0, -25]]] },
            left_forearm: { rotation: [[0, hold.left_forearm], [0.6, [20, 0, 0]], [1.3, [0, 0, 0]], [1.8, [0, 0, 0]]] },
            torso: { rotation: [[0, [0, 0, 0]], [0.6, [-20, 0, 0]], [1.3, [-4, 0, 0]], [1.8, [-4, 0, 0]]] },
            head: { rotation: [[0, [0, 0, 0]], [0.6, [-15, 0, 0]], [1.3, [20, -35, 0]], [1.8, [20, -35, 0]]] },
            cloak: { rotation: [[0, [0, 0, 0]], [1.0, [20, 0, 0]], [1.4, [-5, 0, 3]], [1.8, [-4, 0, 3]]] },
        });
    }

    global.InvasionParts = Object.assign(global.InvasionParts || {}, { necromancerAnimations });
})(window);
