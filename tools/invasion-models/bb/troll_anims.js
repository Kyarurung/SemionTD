// 트롤 투창병 애니메이션: idle / walk / attack / death.
//
// 키프레임 회전 부호는 orc_warrior_anims.js 머리말과 같습니다.
//  x < 0: 몸통·머리는 앞으로 숙이고, 아래로 뻗은 팔·다리는 끝이 뒤로 갑니다(무릎 굽힘은 정강이 x < 0).
//  z > 0: 오른팔(+x)이 바깥으로 벌어집니다.
(function (global) {
    function trollAnimations(B) {
        const A = (name, length, loop, tracks) => InvasionBB.animation(B, name, length, loop, tracks);

        // ------------------------------------------------------------ idle
        // 구부정하게 서서 느리게 숨 쉬고, 긴 팔이 흔들리며 고개를 갸웃합니다.
        A('idle', 2.8, 'loop', {
            torso: { rotation: [[0, [-10, 0, 0]], [1.4, [-13, 0, 0]], [2.8, [-10, 0, 0]]] },
            head: { rotation: [[0, [8, 0, 0]], [0.9, [8, 10, 6]], [2.0, [8, -8, -4]], [2.8, [8, 0, 0]]] },
            right_arm: { rotation: [[0, [8, 0, 4]], [1.4, [12, 0, 6]], [2.8, [8, 0, 4]]] },
            left_arm: { rotation: [[0, [4, 0, -4]], [1.4, [0, 0, -6]], [2.8, [4, 0, -4]]] },
            body: { position: [[0, [0, 0, 0]], [1.4, [0, -0.4, 0]], [2.8, [0, 0, 0]]] },
        });

        // ------------------------------------------------------------ walk
        // 긴 다리로 성큼성큼, 무릎을 크게 굽히고 긴 팔을 반대로 흔듭니다.
        const T = 1.2, q = T / 4, h = T / 2, t3 = 3 * T / 4;
        A('walk', T, 'loop', {
            right_leg: { rotation: [[0, [0, 0, 0]], [q, [26, 0, 0]], [h, [0, 0, 0]], [t3, [-24, 0, 0]], [T, [0, 0, 0]]] },
            left_leg: { rotation: [[0, [0, 0, 0]], [q, [-24, 0, 0]], [h, [0, 0, 0]], [t3, [26, 0, 0]], [T, [0, 0, 0]]] },
            right_shin: { rotation: [[0, [-10, 0, 0]], [q, [-4, 0, 0]], [h, [-10, 0, 0]], [t3, [-40, 0, 0]], [T, [-10, 0, 0]]] },
            left_shin: { rotation: [[0, [-10, 0, 0]], [q, [-40, 0, 0]], [h, [-10, 0, 0]], [t3, [-4, 0, 0]], [T, [-10, 0, 0]]] },
            right_arm: { rotation: [[0, [8, 0, 4]], [q, [-12, 0, 4]], [h, [8, 0, 4]], [t3, [26, 0, 4]], [T, [8, 0, 4]]] },
            left_arm: { rotation: [[0, [0, 0, -4]], [q, [26, 0, -4]], [h, [0, 0, -4]], [t3, [-16, 0, -4]], [T, [0, 0, -4]]] },
            torso: { rotation: [[0, [-14, 0, 0]], [q, [-14, -5, 0]], [h, [-14, 0, 0]], [t3, [-14, 5, 0]], [T, [-14, 0, 0]]] },
            head: { rotation: [[0, [10, 0, 0]], [T, [10, 0, 0]]] },
            body: { position: [[0, [0, -0.6, 0]], [q, [0, 0.4, 0]], [h, [0, -0.6, 0]], [t3, [0, 0.4, 0]], [T, [0, -0.6, 0]]] },
        });

        // ------------------------------------------------------------ attack
        // 투창 던지기: 창 든 팔을 머리 뒤로 젖히고(0.35초) 몸을 비틀며 앞으로 내던집니다(0.5초).
        A('attack', 1.0, 'once', {
            right_arm: { rotation: [[0, [8, 0, 4]], [0.35, [200, 0, 12]], [0.5, [100, 0, 0]], [0.65, [55, 0, -4]], [1.0, [8, 0, 4]]] },
            right_forearm: { rotation: [[0, [0, 0, 0]], [0.35, [-45, 0, 0]], [0.5, [0, 0, 0]], [1.0, [0, 0, 0]]] },
            left_arm: { rotation: [[0, [4, 0, -4]], [0.35, [70, 0, -10]], [0.5, [-10, 0, -15]], [1.0, [4, 0, -4]]] },
            torso: { rotation: [[0, [-10, 0, 0]], [0.35, [8, 25, 0]], [0.5, [-22, -18, 0]], [0.65, [-20, -12, 0]], [1.0, [-10, 0, 0]]] },
            head: { rotation: [[0, [8, 0, 0]], [0.35, [0, -15, 0]], [0.5, [10, 12, 0]], [1.0, [8, 0, 0]]] },
            left_leg: { rotation: [[0, [0, 0, 0]], [0.35, [18, 0, 0]], [0.5, [26, 0, 0]], [1.0, [0, 0, 0]]] },
            left_shin: { rotation: [[0, [0, 0, 0]], [0.5, [-20, 0, 0]], [1.0, [0, 0, 0]]] },
            right_leg: { rotation: [[0, [0, 0, 0]], [0.5, [-16, 0, 0]], [1.0, [0, 0, 0]]] },
            // 0.4초에 창을 놓아 손에서 사라집니다(던진 창은 게임에서 투사체로 날아갑니다).
            javelin: { scale: [[0.35, [1, 1, 1]], [0.4, [0, 0, 0]]] },
        });

        // ------------------------------------------------------------ death
        // 무릎이 꺾여 주저앉았다가 앞으로 길게 엎어집니다.
        A('death', 1.6, 'hold', {
            root: {
                rotation: [[0, [0, 0, 0]], [0.5, [0, 0, 0]], [1.1, [-90, 0, 4]], [1.25, [-85, 0, 4]], [1.4, [-90, 0, 4]]],
                position: [[0, [0, 0, 0]], [0.5, [0, -5, 0]], [1.1, [0, 2.5, 0]], [1.4, [0, 2.5, 0]]],
            },
            right_leg: { rotation: [[0, [0, 0, 0]], [0.5, [45, 0, 0]], [1.1, [8, 0, 4]], [1.6, [8, 0, 4]]] },
            left_leg: { rotation: [[0, [0, 0, 0]], [0.5, [40, 0, 0]], [1.1, [2, 0, -4]], [1.6, [2, 0, -4]]] },
            right_shin: { rotation: [[0, [0, 0, 0]], [0.5, [-80, 0, 0]], [1.1, [-15, 0, 0]], [1.6, [-15, 0, 0]]] },
            left_shin: { rotation: [[0, [0, 0, 0]], [0.5, [-75, 0, 0]], [1.1, [-8, 0, 0]], [1.6, [-8, 0, 0]]] },
            right_arm: { rotation: [[0, [0, 0, 0]], [0.5, [20, 0, 10]], [1.1, [160, 0, 20]], [1.6, [170, 0, 20]]] },
            left_arm: { rotation: [[0, [0, 0, 0]], [0.5, [15, 0, -10]], [1.1, [40, 0, -35]], [1.6, [35, 0, -40]]] },
            torso: { rotation: [[0, [0, 0, 0]], [0.5, [-25, 0, 0]], [1.1, [-5, 0, 0]], [1.6, [-5, 0, 0]]] },
            head: { rotation: [[0, [0, 0, 0]], [0.5, [-10, 0, 0]], [1.1, [25, -40, 0]], [1.6, [25, -40, 0]]] },
        });
    }

    global.InvasionParts = Object.assign(global.InvasionParts || {}, { trollAnimations });
})(window);
