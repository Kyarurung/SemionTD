// 고블린 정찰병 애니메이션: idle / walk / attack / death.
//
// 키프레임 회전 부호는 orc_warrior_anims.js 머리말과 같습니다.
//  x < 0: 몸통·머리는 앞으로 숙이고, 아래로 뻗은 팔·다리는 끝이 뒤로 갑니다.
//  z > 0: 오른팔(+x)이 바깥으로 벌어집니다.
(function (global) {
    function goblinAnimations(B) {
        const A = (name, length, loop, tracks) => InvasionBB.animation(B, name, length, loop, tracks);

        // ------------------------------------------------------------ idle
        // 등을 구부린 채 들썩이며 두리번거리고, 귀가 까딱입니다.
        A('idle', 1.6, 'loop', {
            body: { rotation: [[0, [-8, 0, 0]], [0.8, [-11, 0, 0]], [1.6, [-8, 0, 0]]], position: [[0, [0, 0, 0]], [0.8, [0, -0.3, 0]], [1.6, [0, 0, 0]]] },
            head: { rotation: [[0, [6, 0, 0]], [0.4, [8, 14, 0]], [1.0, [6, -12, 0]], [1.6, [6, 0, 0]]] },
            right_arm: { rotation: [[0, [18, 0, 8]], [0.8, [24, 0, 10]], [1.6, [18, 0, 8]]] },
            left_arm: { rotation: [[0, [10, 0, -8]], [0.8, [6, 0, -10]], [1.6, [10, 0, -8]]] },
            // 귀 키프레임은 기본 기울기에 더해지는 값입니다.
            right_ear: { rotation: [[0, [0, 0, 0]], [0.9, [0, 0, 8]], [1.0, [0, 0, 0]], [1.6, [0, 0, 0]]] },
            left_ear: { rotation: [[0, [0, 0, 0]], [0.3, [0, 0, -8]], [0.4, [0, 0, 0]], [1.6, [0, 0, 0]]] },
        });

        // ------------------------------------------------------------ walk
        // 짧은 다리로 종종거리는 빠른 걸음. 팔을 크게 흔들고 몸이 좌우로 뒤뚱입니다.
        const T = 0.5, q = T / 4, h = T / 2, t3 = 3 * T / 4;
        A('walk', T, 'loop', {
            right_leg: { rotation: [[0, [0, 0, 0]], [q, [35, 0, 0]], [h, [0, 0, 0]], [t3, [-35, 0, 0]], [T, [0, 0, 0]]] },
            left_leg: { rotation: [[0, [0, 0, 0]], [q, [-35, 0, 0]], [h, [0, 0, 0]], [t3, [35, 0, 0]], [T, [0, 0, 0]]] },
            right_arm: { rotation: [[0, [15, 0, 8]], [q, [-25, 0, 8]], [h, [15, 0, 8]], [t3, [45, 0, 8]], [T, [15, 0, 8]]] },
            left_arm: { rotation: [[0, [0, 0, -8]], [q, [40, 0, -8]], [h, [0, 0, -8]], [t3, [-30, 0, -8]], [T, [0, 0, -8]]] },
            body: {
                rotation: [[0, [-14, 0, 0]], [q, [-14, 0, 6]], [h, [-14, 0, 0]], [t3, [-14, 0, -6]], [T, [-14, 0, 0]]],
                position: [[0, [0, 0, 0]], [q, [0, 0.6, 0]], [h, [0, 0, 0]], [t3, [0, 0.6, 0]], [T, [0, 0, 0]]],
            },
            head: { rotation: [[0, [10, 0, 0]], [T, [10, 0, 0]]] },
        });

        // ------------------------------------------------------------ attack
        // 팔을 뒤로 뺐다가(0.15초) 칼로 앞을 푹 찌릅니다(0.28초). 몸도 같이 튀어나갑니다.
        A('attack', 0.55, 'once', {
            right_arm: { rotation: [[0, [18, 0, 8]], [0.15, [-40, 0, 12]], [0.28, [85, 0, -6]], [0.4, [75, 0, -4]], [0.55, [18, 0, 8]]] },
            left_arm: { rotation: [[0, [10, 0, -8]], [0.15, [30, 0, -20]], [0.28, [-20, 0, -12]], [0.55, [10, 0, -8]]] },
            body: {
                rotation: [[0, [-8, 0, 0]], [0.15, [4, 12, 0]], [0.28, [-24, -10, 0]], [0.55, [-8, 0, 0]]],
                position: [[0, [0, 0, 0]], [0.15, [0, 0.4, 0]], [0.28, [0, -0.4, 0]], [0.55, [0, 0, 0]]],
            },
            head: { rotation: [[0, [6, 0, 0]], [0.28, [16, -8, 0]], [0.55, [6, 0, 0]]] },
            right_leg: { rotation: [[0, [0, 0, 0]], [0.28, [-20, 0, 0]], [0.55, [0, 0, 0]]] },
            left_leg: { rotation: [[0, [0, 0, 0]], [0.28, [25, 0, 0]], [0.55, [0, 0, 0]]] },
        });

        // ------------------------------------------------------------ death
        // 펄쩍 뛰었다가 뒤로 벌러덩 넘어져 팔다리를 버둥거린 뒤 멈춥니다.
        A('death', 1.2, 'hold', {
            root: {
                rotation: [[0, [0, 0, 0]], [0.2, [-10, 0, 0]], [0.6, [90, 0, 8]], [0.7, [84, 0, 8]], [0.8, [90, 0, 8]]],
                position: [[0, [0, 0, 0]], [0.2, [0, 1.5, 0]], [0.6, [0, 3, 0]], [0.8, [0, 3, 0]]],
            },
            right_arm: { rotation: [[0, [0, 0, 0]], [0.6, [150, 0, 30]], [0.8, [120, 0, 40]], [1.0, [150, 0, 30]], [1.2, [140, 0, 35]]] },
            left_arm: { rotation: [[0, [0, 0, 0]], [0.6, [150, 0, -30]], [0.9, [120, 0, -40]], [1.2, [140, 0, -35]]] },
            right_leg: { rotation: [[0, [0, 0, 0]], [0.6, [40, 0, 10]], [0.8, [60, 0, 10]], [1.2, [30, 0, 10]]] },
            left_leg: { rotation: [[0, [0, 0, 0]], [0.6, [30, 0, -10]], [0.9, [55, 0, -10]], [1.2, [25, 0, -10]]] },
            head: { rotation: [[0, [0, 0, 0]], [0.6, [20, 25, 0]], [1.2, [20, 30, 0]]] },
        });
    }

    global.InvasionParts = Object.assign(global.InvasionParts || {}, { goblinAnimations });
})(window);
