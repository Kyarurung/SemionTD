// 오우거 투사 애니메이션: idle / walk / attack / death.
//
// 키프레임 회전 부호는 orc_warrior_anims.js 머리말과 같습니다.
//  x < 0: 몸통·머리는 앞으로 숙이고, 아래로 뻗은 팔·다리는 끝이 뒤로 갑니다. z > 0: 오른팔이 바깥으로.
// 몽둥이 방향은 오른 윗팔 + 아래팔 + 손목 x 회전 합이 90이면 곧게 위, 0이면 앞으로 수평, 90을 넘으면 어깨 뒤로 눕습니다.
(function (global) {
    function ogreChampionAnimations(B) {
        const A = (name, length, loop, tracks) => InvasionBB.animation(B, name, length, loop, tracks);
        // 몽둥이를 어깨에 걸쳐 멘 자세
        const hold = { right_arm: [-10, 0, 6], right_forearm: [135, 0, 0], right_hand: [0, 0, 0], left_arm: [4, 0, -6] };
        const keep = (len) => Object.fromEntries(Object.entries(hold).map(([k, v]) => [k, { rotation: [[0, v], [len, v]] }]));

        // ------------------------------------------------------------ idle
        // 배가 크게 오르내리는 느린 숨, 고개를 두리번거립니다.
        A('idle', 3.0, 'loop', Object.assign(keep(3.0), {
            torso: { rotation: [[0, [-2, 0, 0]], [1.5, [1, 0, 0]], [3.0, [-2, 0, 0]]] },
            body: { position: [[0, [0, 0, 0]], [1.5, [0, -0.6, 0]], [3.0, [0, 0, 0]]] },
            head: { rotation: [[0, [2, 0, 0]], [0.9, [2, 12, 0]], [2.1, [2, -10, 0]], [3.0, [2, 0, 0]]] },
            left_arm: { rotation: [[0, hold.left_arm], [1.5, [8, 0, -8]], [3.0, hold.left_arm]] },
        }));

        // ------------------------------------------------------------ walk
        // 무겁게 뒤뚱이는 걸음: 몸통이 좌우로 크게 기울고 착지마다 가라앉습니다.
        const T = 1.4, q = T / 4, h = T / 2, t3 = 3 * T / 4;
        A('walk', T, 'loop', Object.assign(keep(T), {
            right_leg: { rotation: [[0, [0, 0, 0]], [q, [22, 0, 0]], [h, [0, 0, 0]], [t3, [-20, 0, 0]], [T, [0, 0, 0]]] },
            left_leg: { rotation: [[0, [0, 0, 0]], [q, [-20, 0, 0]], [h, [0, 0, 0]], [t3, [22, 0, 0]], [T, [0, 0, 0]]] },
            right_shin: { rotation: [[0, [-5, 0, 0]], [q, [0, 0, 0]], [h, [-5, 0, 0]], [t3, [-22, 0, 0]], [T, [-5, 0, 0]]] },
            left_shin: { rotation: [[0, [-5, 0, 0]], [q, [-22, 0, 0]], [h, [-5, 0, 0]], [t3, [0, 0, 0]], [T, [-5, 0, 0]]] },
            body: {
                rotation: [[0, [0, 0, 0]], [q, [0, -4, 5]], [h, [0, 0, 0]], [t3, [0, 4, -5]], [T, [0, 0, 0]]],
                position: [[0, [0, 0, 0]], [q, [0, -1.2, 0]], [h, [0, 0, 0]], [t3, [0, -1.2, 0]], [T, [0, 0, 0]]],
            },
            torso: { rotation: [[0, [-4, 0, 0]], [T, [-4, 0, 0]]] },
            left_arm: { rotation: [[0, hold.left_arm], [q, [22, 0, -6]], [h, hold.left_arm], [t3, [-14, 0, -6]], [T, hold.left_arm]] },
            head: { rotation: [[0, [4, 0, 0]], [q, [4, 0, -4]], [h, [4, 0, 0]], [t3, [4, 0, 4]], [T, [4, 0, 0]]] },
        }));

        // ------------------------------------------------------------ attack
        // 내려찍기: 몽둥이를 머리 뒤로 크게 치켜들어 몸을 젖혔다가(0.55초) 온몸으로 앞으로 내려칩니다(0.8초).
        A('attack', 1.5, 'once', {
            right_arm: { rotation: [[0, hold.right_arm], [0.55, [165, 0, 12]], [0.8, [60, 0, 2]], [1.05, [58, 0, 2]], [1.5, hold.right_arm]] },
            right_forearm: { rotation: [[0, hold.right_forearm], [0.55, [45, 0, 0]], [0.8, [0, 0, 0]], [1.05, [0, 0, 0]], [1.5, hold.right_forearm]] },
            right_hand: { rotation: [[0, hold.right_hand], [0.55, [0, 0, 0]], [0.8, [-70, 0, 0]], [1.05, [-70, 0, 0]], [1.5, hold.right_hand]] },
            left_arm: { rotation: [[0, hold.left_arm], [0.55, [40, 0, -20]], [0.8, [-20, 0, -12]], [1.5, hold.left_arm]] },
            torso: { rotation: [[0, [0, 0, 0]], [0.55, [12, -15, 0]], [0.8, [-22, 12, 0]], [1.05, [-20, 10, 0]], [1.5, [0, 0, 0]]] },
            head: { rotation: [[0, [2, 0, 0]], [0.55, [-10, 10, 0]], [0.8, [12, -8, 0]], [1.5, [2, 0, 0]]] },
            body: { position: [[0, [0, 0, 0]], [0.55, [0, 0.8, 0]], [0.8, [0, -2.2, 0]], [1.05, [0, -2, 0]], [1.5, [0, 0, 0]]] },
            left_leg: { rotation: [[0, [0, 0, 0]], [0.8, [22, 0, 0]], [1.5, [0, 0, 0]]] },
            left_shin: { rotation: [[0, [0, 0, 0]], [0.8, [-20, 0, 0]], [1.5, [0, 0, 0]]] },
            right_leg: { rotation: [[0, [0, 0, 0]], [0.8, [-14, 0, 0]], [1.5, [0, 0, 0]]] },
        });

        // ------------------------------------------------------------ death
        // 몽둥이를 떨구고 비틀거리다 뒤로 크게 나자빠집니다.
        A('death', 2.0, 'hold', {
            root: {
                rotation: [[0, [0, 0, 0]], [0.6, [-8, 0, 4]], [1.4, [85, 0, -3]], [1.55, [80, 0, -3]], [1.7, [85, 0, -3]]],
                position: [[0, [0, 0, 0]], [0.6, [0, -1, 0]], [1.4, [0, 4, 0]], [1.7, [0, 4, 0]]],
            },
            right_arm: { rotation: [[0, hold.right_arm], [0.6, [20, 0, 20]], [1.4, [-20, 0, 70]], [2.0, [-20, 0, 75]]] },
            right_forearm: { rotation: [[0, hold.right_forearm], [0.6, [20, 0, 0]], [1.4, [10, 0, 0]], [2.0, [10, 0, 0]]] },
            left_arm: { rotation: [[0, hold.left_arm], [0.6, [30, 0, -20]], [1.4, [-20, 0, -70]], [2.0, [-20, 0, -75]]] },
            right_leg: { rotation: [[0, [0, 0, 0]], [0.6, [15, 0, 0]], [1.4, [-10, 0, 8]], [2.0, [-10, 0, 8]]] },
            left_leg: { rotation: [[0, [0, 0, 0]], [0.6, [-5, 0, 0]], [1.4, [20, 0, -8]], [2.0, [20, 0, -8]]] },
            left_shin: { rotation: [[0, [0, 0, 0]], [1.4, [-30, 0, 0]], [2.0, [-30, 0, 0]]] },
            head: { rotation: [[0, [2, 0, 0]], [0.6, [-10, 0, 0]], [1.4, [15, 25, 0]], [2.0, [15, 25, 0]]] },
        });
    }

    global.InvasionParts = Object.assign(global.InvasionParts || {}, { ogreChampionAnimations });
})(window);
