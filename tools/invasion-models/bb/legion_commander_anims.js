// 군단장 애니메이션: idle / walk / attack / death.
//
// 키프레임 회전 부호는 orc_warrior_anims.js 머리말과 같습니다.
//  x < 0: 몸통·머리는 앞으로 숙이고, 아래로 뻗은 팔·다리는 끝이 뒤로 갑니다(무릎 굽힘은 정강이 x < 0).
//  z > 0: 오른팔(+x)이 바깥으로 벌어집니다. 왼팔은 z < 0이 바깥입니다.
(function (global) {
    function commanderAnimations(B) {
        const A = (name, length, loop, tracks) => InvasionBB.animation(B, name, length, loop, tracks);
        // 방패 막기 자세: 방패는 기본 자세에서 앞뒤로 누워 있어서, 아래팔을 앞으로 들면(f 65, 윗팔 a 25와 합쳐 90) 곧게 서고,
        // 윗팔을 안쪽으로 40도 틀면(y -40) 방패 앞면이 옆에서 앞으로 돌아 몸 왼쪽 절반을 가립니다. 눈은 방패 테 위로 보입니다.
        const guard = { left_arm: [25, -40, -5], left_forearm: [65, 0, 0] };
        const guardArm = (x) => [x, guard.left_arm[1], guard.left_arm[2]];

        // ------------------------------------------------------------ idle
        // 방패를 앞에 세워 막으며 무겁게 숨 쉬고 전장을 훑어봅니다. 망토가 천천히 나부낍니다.
        A('idle', 3.0, 'loop', {
            body: { position: [[0, [0, 0, 0]], [1.5, [0, -0.4, 0]], [3.0, [0, 0, 0]]] },
            torso: { rotation: [[0, [0, 0, 0]], [1.5, [-2, 0, 0]], [3.0, [0, 0, 0]]] },
            head: { rotation: [[0, [0, 0, 0]], [1.0, [0, 12, 0]], [2.0, [0, -10, 0]], [3.0, [0, 0, 0]]] },
            // 방패를 앞에 세워 막는 자세로 숨에 맞춰 살짝 들썩입니다.
            left_arm: { rotation: [[0, guard.left_arm], [1.5, guardArm(27)], [3.0, guard.left_arm]] },
            left_forearm: { rotation: [[0, guard.left_forearm], [3.0, guard.left_forearm]] },
            right_arm: { rotation: [[0, [0, 0, 4]], [1.5, [2, 0, 5]], [3.0, [0, 0, 4]]] },
            // 아래팔을 앞으로 들어 소드스태프를 곧게 세워 짚습니다.
            right_forearm: { rotation: [[0, [90, 0, 0]], [3.0, [90, 0, 0]]] },
            cape: { rotation: [[0, [0, 0, 0]], [1.5, [-4, 0, 1]], [3.0, [0, 0, 0]]] },
        });

        // ------------------------------------------------------------ walk
        // 쿵쿵 내딛는 무거운 걸음. 방패는 앞에 든 채 흔들림이 적고, 망토가 뒤로 날립니다.
        const T = 1.3, q = T / 4, h = T / 2, t3 = 3 * T / 4;
        A('walk', T, 'loop', {
            right_leg: { rotation: [[0, [0, 0, 0]], [q, [24, 0, 0]], [h, [0, 0, 0]], [t3, [-22, 0, 0]], [T, [0, 0, 0]]] },
            left_leg: { rotation: [[0, [0, 0, 0]], [q, [-22, 0, 0]], [h, [0, 0, 0]], [t3, [24, 0, 0]], [T, [0, 0, 0]]] },
            right_shin: { rotation: [[0, [-8, 0, 0]], [q, [0, 0, 0]], [h, [-8, 0, 0]], [t3, [-30, 0, 0]], [T, [-8, 0, 0]]] },
            left_shin: { rotation: [[0, [-8, 0, 0]], [q, [-30, 0, 0]], [h, [-8, 0, 0]], [t3, [0, 0, 0]], [T, [-8, 0, 0]]] },
            right_arm: { rotation: [[0, [0, 0, 4]], [q, [-6, 0, 4]], [h, [0, 0, 4]], [t3, [8, 0, 4]], [T, [0, 0, 4]]] },
            right_forearm: { rotation: [[0, [90, 0, 0]], [T, [90, 0, 0]]] },
            left_arm: { rotation: [[0, guard.left_arm], [q, guardArm(28)], [h, guard.left_arm], [t3, guardArm(22)], [T, guard.left_arm]] },
            left_forearm: { rotation: [[0, guard.left_forearm], [T, guard.left_forearm]] },
            torso: { rotation: [[0, [-3, 0, 0]], [q, [-3, -4, 1]], [h, [-3, 0, 0]], [t3, [-3, 4, -1]], [T, [-3, 0, 0]]] },
            body: { position: [[0, [0, 0, 0]], [q, [0, -0.8, 0]], [h, [0, 0, 0]], [t3, [0, -0.8, 0]], [T, [0, 0, 0]]] },
            cape: { rotation: [[0, [-10, 0, 0]], [q, [-14, 0, 2]], [h, [-10, 0, 0]], [t3, [-14, 0, -2]], [T, [-10, 0, 0]]] },
        });

        // ------------------------------------------------------------ attacks
        // 소드스태프 방향은 윗팔(a) + 아래팔(f) + 손목(h)의 x 회전 합으로 정해집니다.
        // 합이 0이면 앞으로 수평, 90이면 곧게 위, 180이면 뒤로 수평입니다(대기 자세는 a 0, f 90, h 0).
        const hold = { right_arm: [0, 0, 4], right_forearm: [90, 0, 0], right_hand: [0, 0, 0] };
        const left = guard;

        // attack_sweep = 가로 휩쓸기: 몸을 오른쪽으로 크게 틀며 날을 오른쪽 옆으로 눕혔다가(0.4초)
        // 왼쪽 앞까지 한 번에 휩쓸어 벱니다(0.65초). 광역 공격용입니다.
        A('attack_sweep', 1.2, 'once', {
            right_arm: { rotation: [[0, hold.right_arm], [0.4, [70, 0, 35]], [0.65, [70, 0, -25]], [0.85, [65, 0, -28]], [1.2, hold.right_arm]] },
            right_forearm: { rotation: [[0, hold.right_forearm], [0.4, [20, 0, 0]], [0.65, [20, 0, 0]], [0.95, [60, 0, 0]], [1.2, hold.right_forearm]] },
            right_hand: { rotation: [[0, hold.right_hand], [0.4, [-90, 0, 0]], [0.65, [-90, 0, 0]], [0.95, [-30, 0, 0]], [1.2, hold.right_hand]] },
            // 몸통 y 회전은 음수면 오른쪽(+x)을, 양수면 왼쪽을 봅니다.
            torso: { rotation: [[0, [0, 0, 0]], [0.4, [2, -40, 0]], [0.65, [-8, 45, 0]], [0.85, [-6, 40, 0]], [1.2, [0, 0, 0]]] },
            head: { rotation: [[0, [0, 0, 0]], [0.4, [0, 25, 0]], [0.65, [0, -25, 0]], [1.2, [0, 0, 0]]] },
            // 휩쓸 때 방패는 몸 앞에서 반대로 당겨 균형을 잡습니다.
            left_arm: { rotation: [[0, left.left_arm], [0.4, [30, -30, -8]], [0.65, [22, -48, -5]], [1.2, left.left_arm]] },
            left_forearm: { rotation: [[0, left.left_forearm], [1.2, left.left_forearm]] },
            body: { position: [[0, [0, 0, 0]], [0.4, [0, -0.6, 0]], [0.65, [0, -1.4, 0]], [1.2, [0, 0, 0]]] },
            left_leg: { rotation: [[0, [0, 0, 0]], [0.65, [18, 0, 0]], [1.2, [0, 0, 0]]] },
            left_shin: { rotation: [[0, [0, 0, 0]], [0.65, [-16, 0, 0]], [1.2, [0, 0, 0]]] },
            right_leg: { rotation: [[0, [0, 0, 0]], [0.65, [-12, 0, 0]], [1.2, [0, 0, 0]]] },
            cape: { rotation: [[0, [0, 0, 0]], [0.4, [-6, 0, -10]], [0.65, [-16, 0, 14]], [1.2, [0, 0, 0]]] },
        });

        // attack(기본) = 내려찍기(가장 자연스러워 기본 공격으로 씁니다): 날을 머리 위 뒤로 넘겨 치켜들었다가(0.45초) 앞 땅까지 내려찍습니다(0.62초).
        A('attack', 1.2, 'once', {
            right_arm: { rotation: [[0, hold.right_arm], [0.45, [160, 0, 10]], [0.62, [45, 0, 0]], [0.8, [42, 0, 0]], [1.2, hold.right_arm]] },
            right_forearm: { rotation: [[0, hold.right_forearm], [0.45, [10, 0, 0]], [0.62, [10, 0, 0]], [0.95, [60, 0, 0]], [1.2, hold.right_forearm]] },
            right_hand: { rotation: [[0, hold.right_hand], [0.45, [-10, 0, 0]], [0.62, [-75, 0, 0]], [0.8, [-75, 0, 0]], [1.2, hold.right_hand]] },
            torso: { rotation: [[0, [0, 0, 0]], [0.45, [12, 12, 0]], [0.62, [-22, -6, 0]], [0.8, [-20, -4, 0]], [1.2, [0, 0, 0]]] },
            head: { rotation: [[0, [0, 0, 0]], [0.45, [10, 0, 0]], [0.62, [-6, 0, 0]], [1.2, [0, 0, 0]]] },
            left_arm: { rotation: [[0, left.left_arm], [0.45, [18, -35, -7]], [0.62, [32, -42, -4]], [1.2, left.left_arm]] },
            left_forearm: { rotation: [[0, left.left_forearm], [1.2, left.left_forearm]] },
            body: { position: [[0, [0, 0, 0]], [0.45, [0, 0.8, 0]], [0.62, [0, -2, 0]], [0.8, [0, -2, 0]], [1.2, [0, 0, 0]]] },
            left_leg: { rotation: [[0, [0, 0, 0]], [0.45, [10, 0, 0]], [0.62, [26, 0, 0]], [1.2, [0, 0, 0]]] },
            left_shin: { rotation: [[0, [0, 0, 0]], [0.62, [-22, 0, 0]], [1.2, [0, 0, 0]]] },
            right_leg: { rotation: [[0, [0, 0, 0]], [0.62, [-16, 0, 0]], [1.2, [0, 0, 0]]] },
            cape: { rotation: [[0, [0, 0, 0]], [0.45, [-4, 0, 0]], [0.62, [-20, 0, 0]], [1.2, [0, 0, 0]]] },
        });

        // attack_thrust = 찌르기: 날을 앞으로 수평으로 눕혀 허리 뒤로 당겼다가(0.35초) 몸을 틀며 앞으로 곧게 찌릅니다(0.5초).
        A('attack_thrust', 0.95, 'once', {
            right_arm: { rotation: [[0, hold.right_arm], [0.35, [-20, 0, 8]], [0.5, [75, 0, -4]], [0.65, [72, 0, -4]], [0.95, hold.right_arm]] },
            right_forearm: { rotation: [[0, hold.right_forearm], [0.35, [80, 0, 0]], [0.5, [5, 0, 0]], [0.65, [8, 0, 0]], [0.95, hold.right_forearm]] },
            right_hand: { rotation: [[0, hold.right_hand], [0.35, [-62, 0, 0]], [0.5, [-66, 0, 0]], [0.65, [-68, 0, 0]], [0.95, hold.right_hand]] },   // 몸을 숙인 만큼 손목을 세워 날을 수평으로
            torso: { rotation: [[0, [0, 0, 0]], [0.35, [4, 22, 0]], [0.5, [-14, -25, 0]], [0.65, [-12, -22, 0]], [0.95, [0, 0, 0]]] },
            head: { rotation: [[0, [0, 0, 0]], [0.35, [0, -12, 0]], [0.5, [0, 18, 0]], [0.95, [0, 0, 0]]] },
            // 찌를 때 방패를 앞으로 밀어 함께 들이받습니다.
            left_arm: { rotation: [[0, left.left_arm], [0.35, [22, -35, -6]], [0.5, [34, -44, -4]], [0.95, left.left_arm]] },
            left_forearm: { rotation: [[0, left.left_forearm], [0.95, left.left_forearm]] },
            body: { position: [[0, [0, 0, 0]], [0.35, [0, 0.3, 0]], [0.5, [0, -1, 0]], [0.95, [0, 0, 0]]] },
            left_leg: { rotation: [[0, [0, 0, 0]], [0.35, [6, 0, 0]], [0.5, [28, 0, 0]], [0.95, [0, 0, 0]]] },
            left_shin: { rotation: [[0, [0, 0, 0]], [0.5, [-20, 0, 0]], [0.95, [0, 0, 0]]] },
            right_leg: { rotation: [[0, [0, 0, 0]], [0.5, [-18, 0, 0]], [0.95, [0, 0, 0]]] },
            cape: { rotation: [[0, [0, 0, 0]], [0.35, [-4, 0, -6]], [0.5, [-14, 0, 8]], [0.95, [0, 0, 0]]] },
        });

        // ------------------------------------------------------------ death
        // 무릎을 꿇고(0.6초) 잠시 버티다가 앞으로 무너집니다. 마지막 자세를 유지합니다.
        A('death', 2.0, 'hold', {
            root: {
                rotation: [[0, [0, 0, 0]], [0.9, [0, 0, 0]], [1.5, [-90, 0, 3]], [1.65, [-86, 0, 3]], [1.8, [-90, 0, 3]]],
                position: [[0, [0, 0, 0]], [0.6, [0, -6, 0]], [0.9, [0, -6, 0]], [1.5, [0, 4, 0]], [1.8, [0, 4, 0]]],
            },
            right_leg: { rotation: [[0, [0, 0, 0]], [0.6, [80, 0, 0]], [0.9, [80, 0, 0]], [1.5, [10, 0, 4]], [2.0, [10, 0, 4]]] },
            left_leg: { rotation: [[0, [0, 0, 0]], [0.6, [30, 0, 0]], [0.9, [30, 0, 0]], [1.5, [4, 0, -4]], [2.0, [4, 0, -4]]] },
            right_shin: { rotation: [[0, [0, 0, 0]], [0.6, [-90, 0, 0]], [0.9, [-90, 0, 0]], [1.5, [-10, 0, 0]], [2.0, [-10, 0, 0]]] },
            left_shin: { rotation: [[0, [0, 0, 0]], [0.6, [-60, 0, 0]], [0.9, [-60, 0, 0]], [1.5, [-6, 0, 0]], [2.0, [-6, 0, 0]]] },
            torso: { rotation: [[0, [0, 0, 0]], [0.6, [-15, 0, 0]], [0.9, [-20, 0, 0]], [1.5, [0, 0, 0]], [2.0, [0, 0, 0]]] },
            head: { rotation: [[0, [0, 0, 0]], [0.6, [-20, 0, 0]], [1.5, [15, 30, 0]], [2.0, [15, 30, 0]]] },
            right_arm: { rotation: [[0, [0, 0, 4]], [0.6, [20, 0, 10]], [1.5, [150, 0, 25]], [2.0, [160, 0, 25]]] },
            right_forearm: { rotation: [[0, [90, 0, 0]], [0.6, [40, 0, 0]], [1.5, [0, 0, 0]], [2.0, [0, 0, 0]]] },
            // 막던 방패를 떨구며 팔이 풀립니다.
            left_arm: { rotation: [[0, guard.left_arm], [0.6, [10, -10, -15]], [1.5, [60, 0, -40]], [2.0, [55, 0, -45]]] },
            left_forearm: { rotation: [[0, guard.left_forearm], [0.6, [20, 0, 0]], [1.5, [0, 0, 0]], [2.0, [0, 0, 0]]] },
            cape: { rotation: [[0, [0, 0, 0]], [0.9, [-10, 0, 0]], [1.5, [-40, 0, 0]], [2.0, [-30, 0, 0]]] },
        });
    }

    global.InvasionParts = Object.assign(global.InvasionParts || {}, { commanderAnimations });
})(window);
